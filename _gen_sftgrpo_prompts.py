"""One-shot generator: extract the VERBATIM training prompt templates from the
GRPO parquet (the authoritative record of what the model was trained on) and emit
`sftgrpo_prompts.py`. Templatizes only the variable spans (proposals JSON,
grounding action/object, referring person/object boxes). Run once:

    cd /workspace/AdaTooler-V/verltool && conda activate verl-tool-env && \
    python /workspace/hoi-benchmarks/_gen_sftgrpo_prompts.py

Re-run if the training prompt ever changes. The emitted module is byte-exact
(verified by _verify_sftgrpo_prompts.py).
"""
import json, re, pandas as pd

PARQUET = "/workspace/AdaTooler-V/verltool/data/train_resampled_moderate.parquet"
OUT = "/workspace/hoi-benchmarks/sftgrpo_prompts.py"

df = pd.read_parquet(PARQUET)

def msgs(i):
    return [dict(m) for m in df.iloc[i]["prompt"]]

def text_of(m):
    c = m["content"]
    if isinstance(c, str):
        return c
    return "".join(x.get("text", "") for x in (dict(z) for z in c)
                   if x.get("type") == "text" or "text" in x)

gi = next(i for i in range(len(df)) if df["extra_info"].iloc[i].get("task_type") == "grounding")
ri = next(i for i in range(len(df)) if df["extra_info"].iloc[i].get("task_type") == "referring")

SYSTEM = text_of(msgs(gi)[0])
ground_user = text_of([m for m in msgs(gi) if m["role"] == "user"][0])
refer_user = text_of([m for m in msgs(ri) if m["role"] == "user"][0])

# --- grounding: replace proposals block + the "Locate ... interact with ..." span ---
g_prop = re.search(r"<candidate_objects>\n(.*?)\n</candidate_objects>", ground_user, re.S).group(1)
ground_t = ground_user.replace(g_prop, "%%PROPOSALS%%", 1)
m = re.search(r"(Locate every person who is )(.*?)( and the )(.*?)( they interact with in this image\.)", ground_t, re.S)
# m.group(2) = "clenching fist" (action+object), group(4) = "fist" (object)
ground_t = ground_t.replace(m.group(0), f"{m.group(1)}%%VERB_OBJ%%{m.group(3)}%%OBJ%%{m.group(5)}", 1)

# --- referring: replace proposals block + person/object box json ---
r_prop = re.search(r"<proposals>\n(.*?)\n</proposals>", refer_user, re.S).group(1)
refer_t = refer_user.replace(r_prop, "%%PROPOSALS%%", 1)
p_json = re.search(r'located at: \*\*(\{"bbox_2d".*?"label": "person"\})\*\*', refer_t).group(1)
o_json = re.search(r'interacting with is located at: \*\*(\{"bbox_2d".*?"label": "object"\})\*\*', refer_t).group(1)
refer_t = refer_t.replace(p_json, "%%PERSON_JSON%%", 1).replace(o_json, "%%OBJECT_JSON%%", 1)

def lit(s):  # safe triple-quoted literal
    return '"""' + s.replace("\\", "\\\\").replace('"""', '\\"\\"\\"') + '"""'

MODULE = f'''"""AUTO-GENERATED by _gen_sftgrpo_prompts.py — DO NOT EDIT BY HAND.

Verbatim HOI training prompts (system + grounding + referring + tool observations),
extracted byte-exact from the GRPO parquet so eval matches SFTv2 + GRPO training.
Verified by _verify_sftgrpo_prompts.py (regenerates the source samples, diffs == 0).

Same prompt is used for BOTH the SFT and GRPO checkpoints (SFT system == GRPO system,
byte-identical). Coordinate scale = 1000x1000 normalized (grid1000).
"""
import json

# Qwen-native tool-calling system prompt (zoom_in requires bbox_2d + target_image).
SYSTEM_PROMPT = {lit(SYSTEM)}

# Post-tool observation strings (the image is attached separately as an image part;
# the <image> placeholder in training corresponds to that image content part).
OBS_ZOOM_IN = "Here is the zoomed-in view of the requested region."
OBS_ZOOM_OUT = "Returned to the full original image view."

_GROUNDING_TEMPLATE = {lit(ground_t)}
_REFERRING_TEMPLATE = {lit(refer_t)}


def format_proposals(proposals: list) -> str:
    """Verbatim training order: bbox_2d, label, confidence, id (indent=2).
    Each proposal dict must provide bbox_1000/bbox_2d, class_name/label, confidence."""
    items = []
    for idx, p in enumerate(proposals):
        bbox = p.get("bbox_2d", p.get("bbox_1000"))
        label = p.get("label", p.get("class_name"))
        items.append({{
            "bbox_2d": bbox,
            "label": label,
            "confidence": round(float(p["confidence"]), 2),
            "id": idx,
        }})
    return json.dumps(items, indent=2)


def build_grounding_user(action: str, object_category: str, proposals: list) -> str:
    """Grounding user message, byte-exact to GRPO training."""
    return (_GROUNDING_TEMPLATE
            .replace("%%PROPOSALS%%", format_proposals(proposals), 1)
            .replace("%%VERB_OBJ%%", f"{{action}} {{object_category}}", 1)
            .replace("%%OBJ%%", object_category, 1))


def build_referring_user(person_box_1000: list, object_box_1000: list, proposals: list) -> str:
    """Referring user message, byte-exact to GRPO training."""
    person_json = json.dumps({{"bbox_2d": list(person_box_1000), "label": "person"}})
    object_json = json.dumps({{"bbox_2d": list(object_box_1000), "label": "object"}})
    return (_REFERRING_TEMPLATE
            .replace("%%PROPOSALS%%", format_proposals(proposals), 1)
            .replace("%%PERSON_JSON%%", person_json, 1)
            .replace("%%OBJECT_JSON%%", object_json, 1))
'''

with open(OUT, "w") as f:
    f.write(MODULE)
print(f"wrote {OUT}")
print("grounding template has %%OBJ%% twice:", ground_t.count("%%OBJ%%"))
print("referring placeholders:", refer_t.count("%%PROPOSALS%%"), refer_t.count("%%PERSON_JSON%%"), refer_t.count("%%OBJECT_JSON%%"))
